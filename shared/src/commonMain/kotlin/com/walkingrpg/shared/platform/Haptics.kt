package com.walkingrpg.shared.platform

/**
 * 振動（architecture.md §1「振動：expect/actual：Vibrator / Core Haptics ＝
 * 歩行中の唯一のフィードバックチャネル」）。
 *
 * [WalkNotifier]（通知）とは別に置く：あちらは「読ませる1本」、こちらは
 * **読ませない印**で、音も文言も出さない（design.md §3「振動1回＝『何かが起きた』の印。
 * それ以上の情報は出さない」「音声・通知文・リアルタイム演出はなし」）。
 *
 * 鳴らせなくても記録の正しさには影響しないので、実装は失敗しても投げない
 * （振動モーターが無い端末・サイレントモード・OSの制限はどれも通常運転）。
 */
interface Haptics {

    /**
     * 短く1回だけ振動する。
     *
     * パターン・強弱・連続は作らない：種類を増やした瞬間に「何が起きたか」が
     * 歩行中に読めてしまい、「中身は帰宅後まで分からない」（design.md §3）が壊れる。
     */
    fun vibrateOnce()
}
